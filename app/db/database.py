def db_list_jobs(limit: int, before: str | None, user_id: int | None = None) -> list[dict]:
    """按创建时间倒序分页查询任务列表, before 为游标时间戳."""
    conditions = []
    params = []
    if user_id is not None:
        conditions.append("jobs.user_id=%s")
        params.append(user_id)
    if before:
        conditions.append("jobs.created_at < %s")
        params.append(before)
    where = " WHERE " + " AND ".join(conditions) if conditions else ""
    with get_db() as conn:
        return conn.execute(
            "SELECT jobs.*, speakers.name AS speaker_name, speakers.icon_path AS speaker_icon_path "
            "FROM jobs LEFT JOIN speakers ON speakers.id=jobs.speaker_id"
            + where + " ORDER BY jobs.created_at DESC LIMIT %s",
            (*params, limit),
        ).fetchall()


def db_recover_jobs() -> list[str]:
    """将中断的执行重新排队, 返回所有待处理任务."""
    with get_db() as conn:
        conn.execute(
            "UPDATE jobs SET status='pending', started_at=NULL, finished_at=NULL, duration_seconds=NULL "
            "WHERE status='running'"
        )
        rows = conn.execute("SELECT id FROM jobs WHERE status='pending' ORDER BY created_at, id").fetchall()
        return [row["id"] for row in rows]


