import psycopg
from psycopg.rows import dict_row

from app.core.config import DATABASE_URL
from app.models.schemas import Job


def get_db(*, connect_timeout: int = 10) -> psycopg.Connection:
    """获取 PostgreSQL 数据库连接."""
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL is required")
    return psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=connect_timeout)


def db_check_connection() -> bool:
    with get_db(connect_timeout=2) as conn:
        conn.execute("SET LOCAL statement_timeout = '2s'")
        conn.execute("SELECT 1")
    return True


def create_tables(conn: psycopg.Connection):
    """在当前事务中创建 PostgreSQL 表和索引."""
    conn.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT NOT NULL UNIQUE,
            password_hash TEXT NOT NULL,
            role TEXT NOT NULL CHECK(role IN ('admin', 'user')),
            is_active INTEGER NOT NULL DEFAULT 1,
            created_at TEXT NOT NULL
        )
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS sessions (
            token_hash TEXT PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(id),
            expires_at TEXT NOT NULL
        )
    """)
    conn.execute("CREATE INDEX IF NOT EXISTS idx_sessions_user_id ON sessions(user_id)")
    conn.execute("""
        CREATE TABLE IF NOT EXISTS api_keys (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(id),
            name TEXT NOT NULL,
            key_hash TEXT NOT NULL UNIQUE,
            prefix TEXT NOT NULL,
            created_at TEXT NOT NULL,
            expires_at TEXT,
            last_used_at TEXT
        )
    """)
    conn.execute("CREATE INDEX IF NOT EXISTS idx_api_keys_user_id ON api_keys(user_id)")
    conn.execute("""
        CREATE TABLE IF NOT EXISTS jobs (
            id TEXT PRIMARY KEY,
            speaker_id BIGINT NOT NULL,
            user_id BIGINT REFERENCES users(id),
            text TEXT NOT NULL,
            status TEXT NOT NULL DEFAULT 'pending',
            created_at TEXT NOT NULL,
            created_ip TEXT,
            result_key TEXT,
            error TEXT
        )
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS speakers (
            id BIGINT PRIMARY KEY,
            name TEXT NOT NULL,
            description TEXT,
            icon_path TEXT,
            prompt_text TEXT,
            prompt_wav_path TEXT,
            reference_wav_path TEXT
        )
    """)
    conn.execute("ALTER TABLE jobs ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES users(id)")
    conn.execute("ALTER TABLE jobs ADD COLUMN IF NOT EXISTS started_at TEXT")
    conn.execute("ALTER TABLE jobs ADD COLUMN IF NOT EXISTS finished_at TEXT")
    conn.execute("ALTER TABLE jobs ADD COLUMN IF NOT EXISTS duration_seconds DOUBLE PRECISION")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_jobs_created_at ON jobs(created_at DESC)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_jobs_user_created_at ON jobs(user_id, created_at DESC)")


def init_db():
    """初始化 PostgreSQL 数据库."""
    with get_db() as conn:
        create_tables(conn)


def db_insert_job(job: Job, user_id: int, max_active_jobs: int, max_jobs_per_hour: int, hour_start: str) -> bool:
    """在单个事务中检查用户任务额度并插入任务."""
    with get_db() as conn:
        # 同一用户的并发提交按行锁串行检查额度.
        conn.execute("SELECT id FROM users WHERE id=%s FOR UPDATE", (user_id,))
        active = conn.execute(
            "SELECT COUNT(*) AS count FROM jobs WHERE user_id=%s AND status IN ('pending', 'running')", (user_id,)
        ).fetchone()["count"]
        if active >= max_active_jobs:
            return False
        recent = conn.execute(
            "SELECT COUNT(*) AS count FROM jobs WHERE user_id=%s AND created_at>=%s", (user_id, hour_start)
        ).fetchone()["count"]
        if recent >= max_jobs_per_hour:
            return False
        conn.execute(
            "INSERT INTO jobs (id, speaker_id, user_id, text, status, created_at, created_ip) "
            "VALUES (%s, %s, %s, %s, %s, %s, %s)",
            (job.id, job.speaker_id, user_id, job.text, job.status, job.created_at, job.created_ip),
        )
        return True


