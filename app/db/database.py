def db_delete_api_key(user_id: int, key_id: int) -> bool:
    with get_db() as conn:
        return conn.execute("DELETE FROM api_keys WHERE id=%s AND user_id=%s", (key_id, user_id)).rowcount > 0


def db_get_api_key_user(key_hash: str, now: str, touch_before: str) -> dict | None:
    with get_db() as conn:
        row = conn.execute(
            "SELECT users.id, users.username, users.role, users.is_active, users.created_at, api_keys.id AS api_key_id "
            "FROM api_keys JOIN users ON users.id=api_keys.user_id "
            "WHERE api_keys.key_hash=%s AND (api_keys.expires_at IS NULL OR api_keys.expires_at>%s) "
            "AND users.is_active=1",
            (key_hash, now),
        ).fetchone()
        if row:
            # 最近使用时间按间隔刷新, 避免轮询请求每次都写库.
            conn.execute(
                "UPDATE api_keys SET last_used_at=%s WHERE id=%s AND (last_used_at IS NULL OR last_used_at<%s)",
                (now, row["api_key_id"], touch_before),
            )
        return row
