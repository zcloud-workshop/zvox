def db_update_user(user_id: int, role: str | None, is_active: bool | None) -> dict | None:
    with get_db() as conn:
        # 所有角色变更共享事务锁, 防止并发停用最后两位管理员.
        conn.execute("SELECT pg_advisory_xact_lock(20261007, 1)")
        row = conn.execute("SELECT * FROM users WHERE id=%s FOR UPDATE", (user_id,)).fetchone()
        if row is None:
            return None
        new_role = role if role is not None else row["role"]
        new_active = int(is_active) if is_active is not None else row["is_active"]
        if row["role"] == "admin" and row["is_active"] and (new_role != "admin" or not new_active):
            active_admins = conn.execute(
                "SELECT COUNT(*) AS count FROM users WHERE role='admin' AND is_active=1"
            ).fetchone()["count"]
            if active_admins <= 1:
                raise ValueError("Cannot disable or demote the last active admin")
        updated = conn.execute(
            "UPDATE users SET role=%s, is_active=%s WHERE id=%s RETURNING *", (new_role, new_active, user_id)
        ).fetchone()
        if not new_active or new_role != row["role"]:
            conn.execute("DELETE FROM sessions WHERE user_id=%s", (user_id,))
            conn.execute("DELETE FROM api_keys WHERE user_id=%s", (user_id,))
        return updated


def db_update_password(user_id: int, password_hash: str) -> bool:
    with get_db() as conn:
        cursor = conn.execute("UPDATE users SET password_hash=%s WHERE id=%s", (password_hash, user_id))
        conn.execute("DELETE FROM sessions WHERE user_id=%s", (user_id,))
        conn.execute("DELETE FROM api_keys WHERE user_id=%s", (user_id,))
        return cursor.rowcount > 0


